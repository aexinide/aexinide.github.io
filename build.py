#!/usr/bin/env python3
"""Builds crawlable blog pages (blog/<slug>/index.html), blog/posts.json, sitemap.xml and feed.xml
from the markdown files in blog/. GitHub Actions runs this on every push; locally: python3 build.py
Needs nothing but Python 3."""
import datetime, email.utils, html, json, re, shutil
from pathlib import Path

SITE = "https://aexinide.github.io/"
NAME, TAGLINE = "AEXINIDE", "AI, robotics, Linux kernels and quantum systems"
ROOT = Path(__file__).resolve().parent
BLOG = ROOT / "blog"
MARK = "<!-- generated by build.py -->"
esc = lambda s: html.escape(str(s), quote=True)

def parse(path):
    text = path.read_text(encoding="utf-8").replace("\r", "")
    meta, body = {}, text
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n?(.*)$", text, re.S)
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                meta[k.strip().lower()] = v.strip().strip('"').strip("'")
        body = m.group(2)
    return meta, body.strip()

def src_url(src):
    if re.match(r"https?://", src, re.I): return src
    if re.match(r"[a-z][a-z0-9+.-]*:", src, re.I): return ""
    return "/blog/" + src.lstrip("./")

def inline(t):
    t = esc(t)
    def img(m):
        u = src_url(m.group(2))
        return f'<img src="{u}" alt="{m.group(1)}" loading="lazy">' if u else ""
    t = re.sub(r"!\[([^\]]*)\]\(([^)\s]+)\)", img, t)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    t = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"\*([^*]+)\*", r"<em>\1</em>", t)
    return re.sub(r"\[([^\]]+)\]\((https?:[^)\s]+)\)", r'<a href="\2" rel="noopener">\1</a>', t)

def md(src):
    out, para, code, lst, in_code = [], [], [], None, False
    def fp():
        nonlocal para
        if para: out.append("<p>" + inline(" ".join(para)) + "</p>"); para = []
    def fl():
        nonlocal lst
        if lst: out.append(f"</{lst}>"); lst = None
    for l in src.split("\n"):
        if l.startswith("```"):
            if in_code: out.append("<pre><code>" + esc("\n".join(code)) + "</code></pre>"); code = []; in_code = False
            else: fp(); fl(); in_code = True
            continue
        if in_code: code.append(l); continue
        if re.match(r"^\s*!\[[^\]]*\]\([^)\s]+\)\s*$", l): fp(); fl(); out.append("<figure>" + inline(l.strip()) + "</figure>"); continue
        m = re.match(r"^(#{1,3})\s+(.*)", l)
        if m: fp(); fl(); n = max(2, len(m.group(1))); out.append(f"<h{n}>{inline(m.group(2))}</h{n}>"); continue
        m = re.match(r"^[-*]\s+(.*)", l) or re.match(r"^\d+\.\s+(.*)", l)
        if m:
            kind = "ul" if re.match(r"^[-*]\s", l) else "ol"
            fp()
            if lst != kind: fl(); out.append(f"<{kind}>"); lst = kind
            out.append("<li>" + inline(m.group(1)) + "</li>"); continue
        if l.startswith(">"): fp(); fl(); out.append("<blockquote>" + inline(re.sub(r"^>\s?", "", l)) + "</blockquote>"); continue
        if not l.strip(): fp(); fl(); continue
        para.append(l)
    fp(); fl()
    if in_code: out.append("<pre><code>" + esc("\n".join(code)) + "</code></pre>")
    return "\n".join(out)

def plain(body):
    t = re.sub(r"```.*?```", " ", body, flags=re.S)
    t = re.sub(r"!\[[^\]]*\]\([^)]*\)", " ", t)
    t = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", t)
    t = re.sub(r"^\s*(#+|[-*>]|\d+\.)\s+", " ", t, flags=re.M)
    t = re.sub(r"[*`_]", "", t)
    return re.sub(r"\s+", " ", t).strip()

def snippet(t, n=155):
    return t if len(t) <= n else t[:n].rsplit(" ", 1)[0].rstrip(",.;:") + "…"

def load_posts():
    posts = []
    for p in sorted(BLOG.glob("*.md")):
        if p.name.startswith("_"): continue
        meta, body = parse(p)
        if meta.get("draft", "").lower() == "true": continue
        dm = re.match(r"(\d{4}-\d{2}-\d{2})", p.stem)
        date = meta.get("date") or (dm.group(1) if dm else "")
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", date):
            print(f"SKIPPED {p.name}: add a date (YYYY-MM-DD) to the header or the file name"); continue
        slug = re.sub(r"^\d{4}-\d{2}-\d{2}-?", "", p.stem)
        if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", slug):
            print(f"SKIPPED {p.name}: use lowercase letters, numbers and dashes only in the file name"); continue
        img = meta.get("image", "")
        if not img:
            m = re.search(r"!\[[^\]]*\]\(([^)\s]+)\)", body); img = m.group(1) if m else ""
        if img and not re.match(r"https?://", img, re.I): img = SITE + "blog/" + img.lstrip("./")
        text = plain(body)
        posts.append(dict(file=p.name, slug=slug, title=meta.get("title") or slug.replace("-", " ").title(), date=date,
            updated=meta.get("updated") or date, tags=[t.strip() for t in meta.get("tags", "").split(",") if t.strip()],
            desc=meta.get("description") or snippet(text), image=img or SITE + "og-image.png", body=body, words=len(text.split())))
    posts.sort(key=lambda x: x["date"], reverse=True)
    return posts

