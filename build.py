def render(p):
    url = f"{SITE}blog/{p['slug']}/"
    person = {"@type": "Person", "@id": SITE + "#person", "name": NAME, "url": SITE}
    ld = {"@context": "https://schema.org", "@graph": [
        {"@type": "BlogPosting", "@id": url + "#post", "headline": p["title"][:110], "description": p["desc"], "url": url,
         "mainEntityOfPage": {"@type": "WebPage", "@id": url}, "datePublished": p["date"], "dateModified": p["updated"],
         "image": p["image"], "inLanguage": "en", "keywords": p["tags"], "wordCount": p["words"],
         "author": person, "publisher": person, "isPartOf": {"@id": SITE + "#website"}},
        {"@type": "BreadcrumbList", "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Home", "item": SITE},
            {"@type": "ListItem", "position": 2, "name": "Blog", "item": SITE + "#blog"},
            {"@type": "ListItem", "position": 3, "name": p["title"], "item": url}]}]}
    rep = {"TITLE": esc(p["title"]), "DESC": esc(p["desc"]), "URL": url, "IMAGE": esc(p["image"]), "DATE": p["date"],
           "UPDATED": p["updated"], "SITE": SITE, "CSS": CSS, "MARK": MARK, "MIN": str(max(1, round(p["words"] / 200))),
           "OGTAGS": "".join(f'<meta property="article:tag" content="{esc(t)}">\n' for t in p["tags"]),
           "TAGS": "".join(f'<span class="tag">{esc(t)}</span>' for t in p["tags"]),
           "LD": json.dumps(ld, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/"), "BODY": md(p["body"])}
    out = PAGE
    for k, v in rep.items(): out = out.replace(f"@@{k}@@", v)
    d = BLOG / p["slug"]; d.mkdir(exist_ok=True)
    (d / "index.html").write_text(out, encoding="utf-8")

def main():
    posts = load_posts()
    keep = {p["slug"] for p in posts}
    for d in BLOG.iterdir():  # remove pages of deleted posts
        f = d / "index.html"
        if d.is_dir() and f.exists() and MARK in f.read_text(encoding="utf-8") and d.name not in keep: shutil.rmtree(d)
    for p in posts: render(p)
    (BLOG / "posts.json").write_text(json.dumps([p["file"] for p in posts], indent=2) + "\n", encoding="utf-8")
    today = datetime.date.today().isoformat()
    urls = [(SITE, max([p["updated"] for p in posts] or [today]))] + [(f"{SITE}blog/{p['slug']}/", p["updated"]) for p in posts]
    (ROOT / "sitemap.xml").write_text('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "".join(f"  <url>\n    <loc>{esc(u)}</loc>\n    <lastmod>{d}</lastmod>\n  </url>\n" for u, d in urls) + "</urlset>\n", encoding="utf-8")
    items = "".join(f"  <item>\n    <title>{esc(p['title'])}</title>\n    <link>{SITE}blog/{p['slug']}/</link>\n    <guid isPermaLink=\"true\">{SITE}blog/{p['slug']}/</guid>\n"
        f"    <pubDate>{email.utils.format_datetime(datetime.datetime.fromisoformat(p['date']).replace(tzinfo=datetime.timezone.utc))}</pubDate>\n"
        f"    <description>{esc(p['desc'])}</description>\n  </item>\n" for p in posts)
    (ROOT / "feed.xml").write_text('<?xml version="1.0" encoding="UTF-8"?>\n<rss version="2.0">\n<channel>\n'
        f"  <title>{NAME} blog</title>\n  <link>{SITE}</link>\n  <description>{esc(TAGLINE)}</description>\n  <language>en</language>\n"
        + items + "</channel>\n</rss>\n", encoding="utf-8")
    print(f"built {len(posts)} post(s): " + ", ".join(f"/blog/{p['slug']}/" for p in posts))

main()
